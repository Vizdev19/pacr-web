export type IconName = keyof typeof ICONS;

export interface IconProps extends Omit<SVGProps<SVGSVGElement>, "name" | "ref" | "children"> {
  name: IconName;
  size?: number;
  strokeWidth?: number;
  color?: string;
  className?: string;
  style?: CSSProperties;
  title?: ReactNode;
}

/** Lucide icon renderer (lucide-react), mapped by kebab-case name. */
export function Icon({ name, size = 18, strokeWidth = 1.75, color = "currentColor", className = "", style, title, ...rest }: IconProps) {
  const Cmp: LucideIcon | undefined = (ICONS as Record<string, LucideIcon | undefined>)[name];
  const common = {
    className: "pc-icon " + className,
    width: size,
    height: size,
    viewBox: "0 0 24 24",
    fill: "none",
    stroke: color,
    strokeWidth,
    strokeLinecap: "round" as const,
    strokeLinejoin: "round" as const,
    "aria-hidden": title ? undefined : true,
    role: title ? "img" : undefined,
    style,
    ...rest,
  };
  if (!Cmp) return <svg {...common}>{title ? <title>{title}</title> : null}</svg>;
  return <Cmp {...common}>{title ? <title>{title}</title> : null}</Cmp>;
}
